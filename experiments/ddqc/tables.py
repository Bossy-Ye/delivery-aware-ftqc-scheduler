"""Render the results tables and the gate evaluation from the data files.

Nothing here is typed in by hand: every number comes from RAW_RESULTS.csv,
CENSUS_SUMMARY.json, ANALYSIS.json and MECHANISM_H1_H2.json, and the output
files (RESULTS_TABLE.md, RESULTS_TABLE.csv, GATES.json, GATES.md) are what the
report quotes.
"""

from __future__ import annotations

import json
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from ftqc_delivery.utils.io import read_csv_rows, write_csv_rows

RESULT_DIR = ROOT / "results" / "ddqc_go_nogo"
REAL_COND = [
    "qt_add8", "qt_sub8", "qt_cadd8", "qt_addk8", "qt_ltc8", "qt_gt8", "qt_equals8",
    "qt_modadd8", "qt_modneg8", "qt_qrom16", "qt_add3", "qt_add4", "qt_equals3", "qt_qrom8", "qb_cc_n12",
]
LOCAL_ONLY = [
    "qb_ipea_n2", "qb_inverseqft_n4", "qb_qec_sm_n5", "qb_shor_n5", "vq_teleportation", "vq_bitflip",
    "vq_phaseflip", "vq_state_injection_T", "mq_ghz_dynamic_6", "mq_iqpe_6", "mq_dynamic_qft_6",
]
CONTROLS = ["ctl_divergent", "ctl_identical"]


def num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def pct(x):
    return f"{100 * x:+.1f}%" if x is not None else "-"


def main() -> None:
    rows = read_csv_rows(RESULT_DIR / "RAW_RESULTS.csv")
    for r in rows:
        for k in list(r):
            v = num(r[k])
            if v is not None and k not in ("commit",) and not k.endswith("_placement"):
                r[k] = v

    # The default probability: 1/2 is physical for qualtran's AND uncomputation
    # (an X-basis measurement), and the no-information prior for the others.
    default = [r for r in rows if r["probability"] == 0.5]

    # Full machine-readable table.
    table_rows = []
    for r in sorted(default, key=lambda r: (r["program"], r["qpus"], r["topology"], r["slack"])):
        table_rows.append({
            "benchmark": r["program"],
            "source": r["source"],
            "commit": r["commit"],
            "qubits": int(r["n_qubits"]),
            "qpus": int(r["qpus"]),
            "capacity": int(r["capacity"]),
            "topology": r["topology"],
            "probability": r["probability"],
            "static_expected_epr": r["flat_expected_epr"],
            "branch_aware_expected_epr": r["expected_expected_epr"],
            "improvement": r["headroom_expected_vs_flat"],
            "case3_expected_epr": r["case3_expected_epr"],
            "static_worst_epr": r["flat_worst_epr"],
            "branch_aware_worst_epr": r["expected_worst_epr"],
            "static_expected_remote": r["flat_expected_remote"],
            "branch_aware_expected_remote": r["expected_expected_remote"],
            "static_max_link_load": r["flat_max_link_load"],
            "branch_aware_max_link_load": r["expected_max_link_load"],
            "blind_expected_epr": r["blind_expected_epr"],
            "placement_changed": int(r["placement_changed"]),
            "static_placement": r["flat_placement"],
            "branch_aware_placement": r["expected_placement"],
            "search": r["flat_method"],
        })
    write_csv_rows(RESULT_DIR / "RESULTS_TABLE.csv", table_rows, list(table_rows[0].keys()))

    lines = [
        "# Results table at the default probability p = 1/2",
        "",
        "Generated by `experiments/ddqc/tables.py` from `RAW_RESULTS.csv`; do not edit by hand.",
        "p = 1/2 is the physical probability of measurement-based AND uncomputation (an X-basis",
        "measurement) and the no-information prior for every other program. Static = Case 1 (every",
        "branch flattened in, weight 1); branch-aware = Case 2 (expected cost, one placement). Costs",
        "are expected EPR pairs. Ties among a compiler's optima are broken in that compiler's favour.",
        "",
        "| Benchmark | Source | QPUs | Topology | Capacity | Static cost | Branch-aware cost | Improvement % | Case 3 cost | Placement changed? |",
        "|---|---|---:|---|---:|---:|---:|---:|---:|---|",
    ]
    for t in table_rows:
        c3 = t["case3_expected_epr"]
        lines.append(
            f"| {t['benchmark']} | {t['source']} | {t['qpus']} | {t['topology']} | {t['capacity']} | "
            f"{t['static_expected_epr']:.2f} | {t['branch_aware_expected_epr']:.2f} | {pct(t['improvement'])} | "
            f"{(f'{c3:.2f}' if isinstance(c3, float) else '-')} | {'yes' if t['placement_changed'] else 'no'} |"
        )
    (RESULT_DIR / "RESULTS_TABLE.md").write_text("\n".join(lines) + "\n")

    # Per-program summary over every network and probability.
    summary = {}
    for name in REAL_COND + LOCAL_ONLY + CONTROLS:
        sub = [r for r in rows if r["program"] == name]
        if not sub:
            continue
        at_half = [r for r in sub if r["probability"] == 0.5]
        heads = [r["headroom_expected_vs_flat"] for r in sub]
        heads_half = [r["headroom_expected_vs_flat"] for r in at_half]
        c3 = [r["headroom_case3_vs_flat"] for r in sub if isinstance(r["headroom_case3_vs_flat"], float)]
        likely_capture = []
        for r in sub:
            gain = r["flat_expected_epr"] - r["expected_expected_epr"]
            if gain > 1e-9:
                likely_capture.append((r["flat_expected_epr"] - r["likely_expected_epr"]) / gain)
        summary[name] = {
            "source": sub[0]["source"],
            "qubits": int(sub[0]["n_qubits"]),
            "conditional_pairs": int(sub[0]["conditional_pairs"]),
            "unconditional_pairs": int(sub[0]["unconditional_pairs"]),
            "cases": len(sub),
            "median_headroom_p_half": round(st.median(heads_half), 4) if heads_half else None,
            "max_headroom_p_half": round(max(heads_half), 4) if heads_half else None,
            "median_headroom_all_p": round(st.median(heads), 4),
            "max_headroom_all_p": round(max(heads), 4),
            "cases_ge10": sum(1 for h in heads if h >= 0.10),
            "cases_ge25": sum(1 for h in heads if h >= 0.25),
            "cases_placement_changed": int(sum(r["placement_changed"] for r in sub)),
            "max_headroom_case3": round(max(c3), 4) if c3 else None,
            "median_heuristic_capture": round(st.median(likely_capture), 4) if likely_capture else None,
        }

    real = [r for r in rows if r["program"] in REAL_COND]
    real_half = [r for r in real if r["probability"] == 0.5]
    local = [r for r in rows if r["program"] in LOCAL_ONLY]
    div = [r for r in rows if r["program"] == "ctl_divergent"]
    ident = [r for r in rows if r["program"] == "ctl_identical"]

    def med(values):
        values = list(values)
        return round(st.median(values), 4) if values else None

    census = json.loads((RESULT_DIR / "CENSUS_SUMMARY.json").read_text())
    mechanism = json.loads((RESULT_DIR / "MECHANISM_H1_H2.json").read_text())

    real_programs_ge25 = sorted({r["program"] for r in real if r["headroom_expected_vs_flat"] >= 0.25})
    real_programs_ge25_half = sorted({r["program"] for r in real_half if r["headroom_expected_vs_flat"] >= 0.25})
    real_programs_ge10 = sorted({r["program"] for r in real if r["headroom_expected_vs_flat"] >= 0.10})
    sources_with_effect = sorted({summary[p]["source"] for p in real_programs_ge10})
    networks_with_effect = sorted({(int(r["qpus"]), r["topology"]) for r in real if r["headroom_expected_vs_flat"] >= 0.10})
    c3_real = [r for r in real if isinstance(r["headroom_case3_vs_flat"], float)]
    c3_gain_over_c2 = [
        (r["expected_expected_epr"] - r["case3_expected_epr"]) / r["expected_expected_epr"]
        for r in c3_real if r["expected_expected_epr"] > 0
    ]
    capture = []
    for r in real:
        gain = r["flat_expected_epr"] - r["expected_expected_epr"]
        if gain > 1e-9:
            capture.append((r["flat_expected_epr"] - r["likely_expected_epr"]) / gain)

    facts = {
        "census": census["ALL"],
        "census_by_source": {k: v for k, v in census.items() if k != "ALL"},
        "real_cases": len(real),
        "real_programs": len({r["program"] for r in real}),
        "real_median_headroom": med(r["headroom_expected_vs_flat"] for r in real),
        "real_median_headroom_p_half": med(r["headroom_expected_vs_flat"] for r in real_half),
        "real_max_headroom": round(max(r["headroom_expected_vs_flat"] for r in real), 4),
        "real_max_headroom_p_half": round(max(r["headroom_expected_vs_flat"] for r in real_half), 4),
        "real_cases_within_10pct": sum(1 for r in real if r["headroom_expected_vs_flat"] < 0.10),
        "real_cases_placement_changed": int(sum(r["placement_changed"] for r in real)),
        "real_cases_placement_changed_p_half": int(sum(r["placement_changed"] for r in real_half)),
        "real_cases_p_half": len(real_half),
        "real_programs_ge25_any_p": real_programs_ge25,
        "real_programs_ge25_p_half": real_programs_ge25_half,
        "real_programs_ge10_any_p": real_programs_ge10,
        "sources_with_ge10": sources_with_effect,
        "networks_with_ge10": [f"{t}{k}" for k, t in networks_with_effect],
        "real_case3_cases": len(c3_real),
        "real_case3_median_extra_over_case2": med(c3_gain_over_c2),
        "real_case3_max_extra_over_case2": round(max(c3_gain_over_c2), 4) if c3_gain_over_c2 else None,
        "real_heuristic_capture_median": med(capture),
        "real_heuristic_capture_cases": len(capture),
        "local_cases": len(local),
        "local_max_headroom": round(max(r["headroom_expected_vs_flat"] for r in local), 4) if local else None,
        "divergent_control_max_headroom": round(max(r["headroom_expected_vs_flat"] for r in div), 4),
        "divergent_control_median_headroom": med(r["headroom_expected_vs_flat"] for r in div),
        "divergent_control_placement_changed": int(sum(r["placement_changed"] for r in div)),
        "divergent_control_cases": len(div),
        "divergent_control_max_case3": round(max(r["headroom_case3_vs_flat"] for r in div if isinstance(r["headroom_case3_vs_flat"], float)), 4),
        "identical_control_max_headroom": round(max(r["headroom_expected_vs_flat"] for r in ident), 4),
        "mechanism_case2_identical_for_twins": mechanism["case2_identical_for_exclusive_and_independent_twins"],
        "mechanism_divergent_headroom_at_half": mechanism["divergent_headroom_at_p_half"],
        "real_headroom_by_probability": {
            str(p): med(r["headroom_expected_vs_flat"] for r in real if r["probability"] == p)
            for p in sorted({r["probability"] for r in real})
        },
        "real_headroom_by_topology": {
            t: med(r["headroom_expected_vs_flat"] for r in real if r["topology"] == t)
            for t in ("line", "ring", "grid", "full")
        },
        "real_max_headroom_by_topology": {
            t: round(max([r["headroom_expected_vs_flat"] for r in real if r["topology"] == t] or [0]), 4)
            for t in ("line", "ring", "grid", "full")
        },
        "real_headroom_by_slack": {
            str(int(s)): med(r["headroom_expected_vs_flat"] for r in real if r["slack"] == s) for s in (0.0, 2.0)
        },
        "real_max_headroom_by_slack": {
            str(int(s)): round(max([r["headroom_expected_vs_flat"] for r in real if r["slack"] == s] or [0]), 4)
            for s in (0.0, 2.0)
        },
        "real_headroom_by_qpus": {
            str(int(k)): med(r["headroom_expected_vs_flat"] for r in real if r["qpus"] == k) for k in (2.0, 3.0, 4.0)
        },
        "real_blind_vs_aware_median": med(r["headroom_expected_vs_blind"] for r in real),
        "per_program": summary,
    }
    (RESULT_DIR / "FACTS.json").write_text(json.dumps(facts, indent=2))
    print(json.dumps({k: v for k, v in facts.items() if k not in ("per_program", "census_by_source")}, indent=1))


if __name__ == "__main__":
    main()
