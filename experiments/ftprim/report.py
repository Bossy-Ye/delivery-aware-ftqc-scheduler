"""Generate REPORT.md from SUMMARY.json, FITS.json and MECHANISM.json only.

Usage:  python experiments/ftprim/report.py RESULT_DIR

Every number in the report is read from those files; the prose around them is
fixed text that states what each number is.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def fmt(x, digits=3):
    if x is None:
        return "n/a"
    if isinstance(x, str):
        return x
    if isinstance(x, bool):
        return "yes" if x else "no"
    if x != x:
        return "n/a"
    if x in (float("inf"), -float("inf")):
        return "inf" if x > 0 else "-inf"
    if x == 0:
        return "0"
    if abs(x) >= 1000 or abs(x) < 1e-2:
        return f"{x:.{digits - 1}e}"
    return f"{x:.{digits}g}"


def pct(x):
    return "n/a" if x is None or x != x else f"{100 * x:.0f}%"


def ci(pair):
    if not pair:
        return ""
    return f" [{fmt(pair[0])}, {fmt(pair[1])}]"


GATE_TEXT = {
    "G1": "repeated disagreement on realistic instances (>= 50% with >= 10% of decisions differing)",
    "G2": "G1 and G3 in >= 2 realistic regimes",
    "G3": "median F_A/F_C >= 10 in a realistic regime",
    "G4": "C within 3x ebits and 2x latency of A where it wins (>= 75%)",
    "G5": "best fixed K recovers < 80% of the oracle benefit (realistic)",
    "G6": "no existing compiler already chooses remote primitives by logical failure",
    "G7": "per-regime K recovers < 95% and realistic K* varies >= 3x",
}


def main() -> None:
    d = Path(sys.argv[1])
    S = json.load(open(d / "SUMMARY.json"))
    F = json.load(open(d / "FITS.json"))
    M = json.load(open(d / "MECHANISM.json")) if (d / "MECHANISM.json").exists() else {}
    v, wl = S["verdict"], S["workloads"]
    L = []
    add = L.append
    add("# FT remote-primitive choice: GO/NO-GO report\n")
    add(f"**Decision: {S['decision']}**\n")
    add("Generated by `experiments/ftprim/report.py` from `SUMMARY.json`, `FITS.json` and "
        "`MECHANISM.json`. Criteria and regime classes are those frozen in `EXPERIMENT_CONTRACT.md`.\n")

    add("## 1. Frozen criteria\n")
    add("| criterion | meaning | result |\n| --- | --- | --- |")
    for g, ok in v["gates"].items():
        add(f"| {g} | {GATE_TEXT.get(g, '')} | {'pass' if ok else 'fail'} |")
    add("\n| NO_GO trigger | fired? |\n| --- | --- |")
    for t, hit in v["no_go_triggers"].items():
        add(f"| {t.replace('_', ' ')} | {'**FIRED**' if hit else 'no'} |")
    add("")

    add("## 2. Real workloads (A = ebit-optimal, B = burst threshold, C = failure-optimal)\n")
    add(f"Communicating workloads (>= 10 non-local CNOTs under the static partition): "
        f"{len(wl['communicating_workloads'])} of {len({*wl['per_workload']} | set())} listed below; "
        f"instances: {wl['instances']} in total, {wl['realistic_instances']} communicating x realistic.")
    add(f"Solver: ebit-optimal A proven optimal in {wl['solver_status']['A_ebit_optimal_proven']} of "
        f"{wl['solver_status']['instances']} instances, failure-optimal C in "
        f"{wl['solver_status']['C_optimal_proven']} (the rest carry the CP-SAT bound).\n")
    add("| regime class | instances | share with >= 10% decisions differing | median disagreement | "
        "median F_A/F_C | max F_A/F_C | share F_A/F_C >= 1.25 | C wins | C ebits / A ebits (median, max) | "
        "per-regime K recovers | best fixed K (recovers) |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for cls, c in wl["by_class"].items():
        add(f"| {cls} | {c['instances']} | {pct(c['share_disagree_ge_10pct'])} | {fmt(c['median_disagreement'])} | "
            f"{fmt(c['median_failure_ratio'])} | {fmt(c['max_failure_ratio'])} | {pct(c['share_ratio_ge_1_25'])} | "
            f"{c['c_wins']} | {fmt(c['c_ebit_overhead_median'])}, {fmt(c['c_ebit_overhead_max'])} | "
            f"{pct(c['hardware_conditioned_recovery'])} | {c['best_fixed_K']} ({pct(c['best_fixed_recovery'])}) |")
    add("\nRecovery = sum(F_A - F_B) / sum(F_A - F_C); it is negative when the threshold rule is worse than "
        "the ebit-optimal baseline and is ill-conditioned when the oracle benefit is near zero "
        f"(realistic total benefit {fmt(wl['by_class'].get('realistic', {}).get('total_benefit'))} expected faults).\n")
    add("| realistic regime | workloads | median F_A/F_C | max F_A/F_C | share disagree >= 10% | "
        "median ratio bound from solver | C proven optimal |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for reg, r in wl["per_realistic_regime"].items():
        add(f"| {reg} | {r['workloads']} | {fmt(r['median_failure_ratio'])} | {fmt(r['max_failure_ratio'])} | "
            f"{pct(r['share_disagree_ge_10pct'])} | {fmt(r.get('median_failure_ratio_upper_bound'))} | "
            f"{pct(r.get('solver_optimal_share'))} |")
    add("\n| workload | category | static non-local CNOTs | max F_A/F_C (regime) | max F_A/F_C in realistic |")
    add("| --- | --- | --- | --- | --- |")
    for name, w in sorted(wl["per_workload"].items()):
        add(f"| {name} | {w['category']} | {int(w['static_remote'])} | {fmt(w['max_ratio'])} "
            f"({w['max_ratio_regime'] or '-'}) | {fmt(w['realistic_max_ratio'])} |")
    add("")
    if S.get("sensitivity"):
        add("Capacity sensitivity (reduced solver limits, see section 7):\n")
        for tag, sv in S["sensitivity"].items():
            s = sv["summary"]
            add(f"* {tag}: decision under the same criteria {sv['verdict']['decision']}; realistic share "
                f"disagreeing >= 10%: {pct(s['g1_share_instances_disagree_ge_10pct'])}; median F_A/F_C by realistic "
                f"regime: {', '.join(fmt(x) for x in s['median_failure_ratio_by_realistic_regime'].values())}.")
        add("")

    B = json.load(open(d / "BOUNDS.json")) if (d / "BOUNDS.json").exists() else None
    if B:
        bs = B["summary"]
        add("Solver-independent bound on the true benefit F(A*)/F(C*) (`bounds.py`; valid whatever the "
            "solver proved, tight when entanglement generation dominates):\n")
        add("| regime class | instances | median bound | max bound |\n| --- | --- | --- | --- |")
        for cls in ("realistic", "near-term", "idealised"):
            if cls in bs:
                add(f"| {cls} | {bs[cls]['instances']} | {fmt(bs[cls]['median_bound'])} | {fmt(bs[cls]['max_bound'])} |")
        add("\nMax bound per realistic regime: " + ", ".join(
            f"{k}: {fmt(x)}" for k, x in bs["realistic_by_regime_max_bound"].items()) + ".\n")

    add("## 3. Clean pattern (one block, k = 1..30 interactions)\n")
    add("| class / scenario | points | inversions | ebits teleport, failure keeps remote | ebits remote, "
        "failure teleports | median ratio | max ratio | ratio >= 10 |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for k, c in S["clean_pattern"].items():
        add(f"| {k} | {c['points']} | {c['inversions']} | {c['ebits_teleport_failure_remote']} | "
            f"{c['ebits_remote_failure_teleport']} | {fmt(c['failure_ratio_median'])} | "
            f"{fmt(c['failure_ratio_max'])} | {c['failure_ratio_ge_10']} |")
    add("")
    for scen, t in S["clean_thresholds"].items():
        add(f"* {scen}: best single K = {t['best_fixed_K']} (decision agreement "
            f"{pct(t['best_fixed']['decision_agreement'])}, benefit recovered "
            f"{pct(t['best_fixed']['benefit_recovered'])}); K per regime: agreement "
            f"{pct(t['hardware_conditioned']['decision_agreement'])}, recovered "
            f"{pct(t['hardware_conditioned']['benefit_recovered'])}; the paper's K = 10: agreement "
            f"{pct(t['paper_rule_K10']['decision_agreement'])}, recovered "
            f"{pct(t['paper_rule_K10']['benefit_recovered'])}; ebit rule: agreement "
            f"{pct(t['ebit_rule']['decision_agreement'])}.")
    add(f"* Realistic break-even k (one-way): {v['realistic_kstars']} (spread {fmt(v['realistic_kstar_spread'])}x).\n")

    add("## 4. Calibrated costs (TMCBS circuits, Tesseract; 95% bootstrap intervals)\n")
    add("| point | n | s_mem per block-round | delta = b_R - b_T | c_tel = a_T - a_R | K* one-way | K* return |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for name, f in sorted(F["fits"].items(), key=lambda kv: (kv[1]["code"], kv[1]["p"], kv[1]["ratio"])):
        dd, cc = f["derived"], f["ci"]
        flag = " (return assumed = outbound)" if dd.get("assumed_return") else ""
        add(f"| {name}{flag} | {f['n']} | {fmt(dd['s_mem'])} | {fmt(dd['delta'])}{ci(cc.get('delta'))} | "
            f"{fmt(dd['c_tel'])}{ci(cc.get('c_tel'))} | {fmt(dd.get('k_star_oneway'))}{ci(cc.get('k_star_oneway'))} | "
            f"{fmt(dd.get('k_star_return'))}{ci(cc.get('k_star_return'))} |")
    hold = S.get("holdout") or {}
    flat = [h for hs in hold.values() for h in hs]
    if flat:
        inside = sum(1 for h in flat if h["inside_ci"])
        add(f"\nAdditivity hold-out (SC d=3, k = 8): {inside}/{len(flat)} predictions inside the simulated "
            f"Bayes intervals (contract threshold 80%).\n")

    if M:
        add("## 5. Mechanism\n")
        split = M.get("teleport_overhead_split", {})
        if split:
            add("| point | c_tel | share from Bell-pair block settling | share from Bell measurement + feed-forward "
                "| remaining (ebit Bell pair, extra rounds) | K* without both |")
            add("| --- | --- | --- | --- | --- | --- |")
            for name, e in split.items():
                add(f"| {name} | {fmt(e['c_tel'])} | {pct(e.get('share_bell_block_settle'))} | "
                    f"{pct(e.get('share_bsm_feedforward'))} | {pct(e.get('share_remaining'))} | "
                    f"{fmt(e.get('k_star_without_both'))} |")
            add("")
        rho = M.get("break_even_k_vs_rho", {})
        if rho:
            add("Break-even k (one-way) as entanglement generation slows (rho = rounds per batch; "
                "`None` = never teleports within k <= 30):\n")
            add("| point | " + " | ".join(f"rho={r}" for r in sorted({x for v2 in rho.values() for x in v2}, key=float)) + " |")
            cols = sorted({x for v2 in rho.values() for x in v2}, key=float)
            add("| --- | " + " | ".join("---" for _ in cols) + " |")
            for name, row in sorted(rho.items()):
                add(f"| {name} | " + " | ".join(str(row.get(c)) for c in cols) + " |")
            add("")
    (d / "REPORT.md").write_text("\n".join(L) + "\n")
    print(f"wrote {d / 'REPORT.md'} ({len(L)} lines)")


if __name__ == "__main__":
    main()
