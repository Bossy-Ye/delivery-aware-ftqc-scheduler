"""Generate REPORT.md from SUMMARY.json, FITS.json and MECHANISM.json only.

Usage:  python experiments/ftprim/report.py RESULT_DIR
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def fmt(x, digits=3):
    if x is None:
        return "n/a"
    if isinstance(x, str):
        return x
    if x != x:
        return "n/a"
    if x == float("inf"):
        return "inf"
    if abs(x) >= 1000 or (abs(x) < 1e-2 and x != 0):
        return f"{x:.{digits - 1}e}"
    return f"{x:.{digits}g}"


def ci(pair):
    if not pair:
        return ""
    return f" [{fmt(pair[0])}, {fmt(pair[1])}]"


def main() -> None:
    d = Path(sys.argv[1])
    S = json.load(open(d / "SUMMARY.json"))
    F = json.load(open(d / "FITS.json"))
    M = json.load(open(d / "MECHANISM.json")) if (d / "MECHANISM.json").exists() else {}
    v, wl = S["verdict"], S["workloads"]
    L = []
    add = L.append
    add("# FT remote-primitive choice: GO/NO-GO report\n")
    add(f"**Decision: {S['decision']}**\n")
    add("Generated by `experiments/ftprim/report.py` from `SUMMARY.json`, `FITS.json` and "
        "`MECHANISM.json`; no number below is typed by hand.\n")

    add("## Criteria (EXPERIMENT_CONTRACT.md section 9)\n")
    add("| criterion | result |\n| --- | --- |")
    for g, ok in v["gates"].items():
        add(f"| {g} | {'pass' if ok else 'fail'} |")
    for t, hit in v["no_go_triggers"].items():
        add(f"| NO_GO trigger: {t.replace('_', ' ')} | {'FIRED' if hit else 'no'} |")
    add("")
    add(f"* Realistic communicating instances: {wl['realistic_instances']}; share with decision "
        f"disagreement >= 10%: {fmt(wl['g1_share_instances_disagree_ge_10pct'])}; share with < 5%: "
        f"{fmt(wl['share_instances_disagree_lt_5pct'])}.")
    add(f"* Median F_A/F_C per realistic regime: " + ", ".join(
        f"{k}: {fmt(x)}" for k, x in wl["median_failure_ratio_by_realistic_regime"].items()) + ".")
    add(f"* Best fixed K = {wl['best_fixed_K']} recovers {fmt(wl['best_fixed_recovery'])} of the oracle "
        f"benefit; K per regime recovers {fmt(wl['hardware_conditioned_recovery'])}; the paper's K = 10 "
        f"recovers {fmt(wl['paper_K10_recovery'])} (total realistic benefit "
        f"{fmt(wl['total_oracle_benefit_realistic'])} expected faults).")
    add(f"* Realistic break-even k (clean pattern, one-way): {v['realistic_kstars']}; spread "
        f"{fmt(v['realistic_kstar_spread'])}x.")
    add(f"* Real-workload inversions (disagreement >= 10% and F_A/F_C >= 1.1) by regime class: "
        f"{wl['workload_inversions_any_regime_by_class']}.\n")

    add("## Calibrated costs (TMCBS circuits, Tesseract)\n")
    add("| point | n | s_mem | delta = b_R - b_T | c_tel = a_T - a_R | K* one-way | K* return |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for name, f in sorted(F["fits"].items()):
        dd, cc = f["derived"], f["ci"]
        add(f"| {name} | {f['n']} | {fmt(dd['s_mem'])} | {fmt(dd['delta'])}{ci(cc.get('delta'))} | "
            f"{fmt(dd['c_tel'])}{ci(cc.get('c_tel'))} | {fmt(dd.get('k_star_oneway'))}{ci(cc.get('k_star_oneway'))} | "
            f"{fmt(dd.get('k_star_return'))}{ci(cc.get('k_star_return'))} |")
    add("")
    hold = S.get("holdout") or {}
    flat = [h for hs in hold.values() for h in hs]
    if flat:
        inside = sum(1 for h in flat if h["inside_ci"])
        add(f"Additivity hold-out (k = 8): {inside}/{len(flat)} predictions inside the simulated Bayes "
            f"interval.\n")

    add("## Clean pattern (k = 1..30)\n")
    add("| class / scenario | points | inversions | ebits->T, failure->R | ebits->R, failure->T | "
        "median ratio | max ratio | ratio >= 10 |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for k, c in S["clean_pattern"].items():
        add(f"| {k} | {c['points']} | {c['inversions']} | {c['ebits_teleport_failure_remote']} | "
            f"{c['ebits_remote_failure_teleport']} | {fmt(c['failure_ratio_median'])} | "
            f"{fmt(c['failure_ratio_max'])} | {c['failure_ratio_ge_10']} |")
    add("")
    for scen, t in S["clean_thresholds"].items():
        add(f"* {scen}: best fixed K = {t['best_fixed_K']} (agreement {fmt(t['best_fixed']['decision_agreement'])}, "
            f"benefit recovered {fmt(t['best_fixed']['benefit_recovered'])}); per-regime K: agreement "
            f"{fmt(t['hardware_conditioned']['decision_agreement'])}, recovered "
            f"{fmt(t['hardware_conditioned']['benefit_recovered'])}; paper K = 10: agreement "
            f"{fmt(t['paper_rule_K10']['decision_agreement'])}, recovered "
            f"{fmt(t['paper_rule_K10']['benefit_recovered'])}; ebit rule: agreement "
            f"{fmt(t['ebit_rule']['decision_agreement'])}.")
    add("")

    add("## Workloads by realistic regime\n")
    add("| regime | workloads | median F_A/F_C | max F_A/F_C | share disagree >= 10% | median disagreement |")
    add("| --- | --- | --- | --- | --- | --- |")
    for reg, r in wl["per_realistic_regime"].items():
        add(f"| {reg} | {r['workloads']} | {fmt(r['median_failure_ratio'])} | {fmt(r['max_failure_ratio'])} | "
            f"{fmt(r['share_disagree_ge_10pct'])} | {fmt(r['median_disagreement'])} |")
    add("")

    if M:
        add("## Mechanism\n")
        for name, e in M.get("teleport_overhead_split", {}).items():
            add(f"* {name}: c_tel {fmt(e['c_tel'])}; Bell-block settling share "
                f"{fmt(e.get('share_bell_block_settle'))}; Bell-measurement/feed-forward share "
                f"{fmt(e.get('share_bsm_feedforward'))}; remaining (ebit Bell pair, extra rounds) "
                f"{fmt(e.get('share_remaining'))}.")
        add("")
    (d / "REPORT.md").write_text("\n".join(L) + "\n")
    print((d / "REPORT.md").read_text()[:2000])


if __name__ == "__main__":
    main()
